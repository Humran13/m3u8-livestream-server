port_listening() {
    local port="$1"
    if command_exists ss; then
        ss -tln 2>/dev/null | awk '{print $4}' | grep -qE "[.:]${port}\$"
    elif command_exists netstat; then
        netstat -tln 2>/dev/null | awk '{print $4}' | grep -qE "[.:]${port}\$"
    else
        return 2
    fi
}
